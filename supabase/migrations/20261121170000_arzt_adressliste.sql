-- Ärzte-Adressliste: augenärztliche Praxen und Kliniken, von denen Rezepte
-- kommen (Stammdaten > Ärzte). Neue Tabelle, keine Änderung an bestehenden
-- Daten. Einträge werden über die App angelegt, nicht per Migration.

create table if not exists public.arzt (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Name" text,
  "Praxis" text,
  "Fachrichtung" text,
  "LANR" text,
  "BSNR" text,
  "Straße" text,
  "PLZ" text,
  "Ort" text,
  "Telefon" text,
  "Fax" text,
  "Email" text,
  "Bemerkung" text,
  constraint arzt_name_oder_praxis check (
    coalesce(btrim("Name"), '') <> '' or coalesce(btrim("Praxis"), '') <> ''
  )
);

comment on table public.arzt is
  'Ärzte-Adressliste: augenärztliche Praxen und Kliniken (verordnende Ärzte).';
comment on column public.arzt."Name" is
  'Titel und Name des Arztes bzw. der Ärzte, z. B. "Dr. med. Ulrich Voigt".';
comment on column public.arzt."Praxis" is
  'Praxis, Klinik oder Berufsausübungsgemeinschaft (BAG).';
comment on column public.arzt."LANR" is
  'Lebenslange Arztnummer (9-stellig).';
comment on column public.arzt."BSNR" is
  'Betriebsstättennummer (9-stellig).';

create index if not exists arzt_name_idx on public.arzt ("Name");
create index if not exists arzt_praxis_idx on public.arzt ("Praxis");

alter table public.arzt enable row level security;

drop policy if exists rolle_lesen on public.arzt;
create policy rolle_lesen on public.arzt
  for select to authenticated using ((select public.darf_lesen()));
drop policy if exists rolle_anlegen on public.arzt;
create policy rolle_anlegen on public.arzt
  for insert to authenticated with check ((select public.darf_bearbeiten()));
drop policy if exists rolle_aendern on public.arzt;
create policy rolle_aendern on public.arzt
  for update to authenticated
  using ((select public.darf_bearbeiten())) with check ((select public.darf_bearbeiten()));
drop policy if exists rolle_loeschen on public.arzt;
create policy rolle_loeschen on public.arzt
  for delete to authenticated using ((select public.darf_bearbeiten()));

revoke all on public.arzt from anon;

drop trigger if exists aenderung_protokollieren on public.arzt;
create trigger aenderung_protokollieren
  after insert or update or delete on public.arzt
  for each row execute function public.protokolliere_aenderung();
