-- Glas-Lager: fertige Einstärken-Lagergläser mit Stückzahl. Der Glas-Finder
-- in der Brillen-Karteikarte sucht hier passende Gläser zu den Werten des
-- Auftrags und bucht ein übernommenes Glas mit glaslager_abbuchen ab.
-- Neue, leere Tabelle; keine Kundendaten.

create table if not exists public.glaslager (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Hersteller" text,
  "Bezeichnung" text not null,
  "Brechungsindex" numeric(4, 3),
  "Verguetung" text,
  "Durchmesser" smallint,
  -- Lagerglas in Minuszylinder-Schreibweise (Cyl <= 0)
  "Sph" numeric(5, 2) not null,
  "Cyl" numeric(5, 2) not null default 0 check ("Cyl" <= 0),
  "Bestand" integer not null default 0 check ("Bestand" >= 0),
  "Mindestbestand" integer not null default 0 check ("Mindestbestand" >= 0),
  "Verkaufspreis" numeric(10, 2),
  "Lagerort" text,
  "Aktiv" boolean not null default true
);

create index if not exists glaslager_werte_idx
  on public.glaslager ("Sph", "Cyl");

alter table public.glaslager enable row level security;

drop policy if exists "glaslager_angemeldet" on public.glaslager;
create policy "glaslager_angemeldet" on public.glaslager
  for all to authenticated
  using (true)
  with check (true);

-- Ein Glas abbuchen (Glas-Finder). Gibt den neuen Bestand zurück; ist keins
-- mehr da, bricht die Funktion mit einer verständlichen Meldung ab.
create or replace function public.glaslager_abbuchen(p_id bigint)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_bestand integer;
begin
  update public.glaslager
  set "Bestand" = "Bestand" - 1
  where id = p_id and "Bestand" > 0
  returning "Bestand" into v_bestand;
  if v_bestand is null then
    raise exception 'Dieses Lagerglas ist nicht mehr vorrätig.';
  end if;
  return v_bestand;
end;
$$;

revoke all on function public.glaslager_abbuchen(bigint) from public;
grant execute on function public.glaslager_abbuchen(bigint) to authenticated;
