-- Honorar- bzw. Firmenrechnungen (z. B. Gesundheitstag bei einer Firma),
-- unabhängig von Kunden und Aufträgen. Die Rechnungsnummer kommt aus
-- derselben fortlaufenden Reihe wie die Kundenrechnungen
-- (rechnungsnummer_stand), vergeben beim Anlegen in
-- firmenrechnung_anlegen(). Eine gestellte Rechnung wird nicht geändert:
-- nur Lesen und Anlegen. Neue Tabelle, keine Änderung an bestehenden Daten.

create table if not exists public.firmenrechnung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Rechnungsnummer" text not null unique,
  "Rechnungsdatum" date not null default current_date,
  "Empfaenger" text not null check (length(trim("Empfaenger")) > 0),
  "Auftragsnummer" text,
  "Leistungsdatum" date,
  "Zeit" text,
  "Ort" text,
  "Ansprechpartner" text,
  "Aktivitaet" text,
  "Beschreibung" text,
  "Positionen" jsonb not null default '[]'::jsonb,
  "Kilometer" numeric(8, 1) not null default 0 check ("Kilometer" >= 0),
  "KmSatz" numeric(6, 2) not null default 0.30 check ("KmSatz" >= 0),
  "MwStSatz" numeric(4, 1) not null default 19 check ("MwStSatz" >= 0),
  "Netto" numeric(10, 2) not null default 0,
  "MwSt" numeric(10, 2) not null default 0,
  "Brutto" numeric(10, 2) not null default 0,
  "Bemerkung" text,
  erstellt_von text
);

comment on table public.firmenrechnung is
  'Honorar-/Firmenrechnungen ohne Kundenbezug; Nummer aus rechnungsnummer_stand über firmenrechnung_anlegen().';
comment on column public.firmenrechnung."Positionen" is
  'Liste [{"zeitaufwand","aktivitaet","betrag"}], Beträge netto.';

create index if not exists firmenrechnung_datum_idx
  on public.firmenrechnung ("Rechnungsdatum" desc);

alter table public.firmenrechnung enable row level security;

drop policy if exists "firmenrechnung_lesen" on public.firmenrechnung;
create policy "firmenrechnung_lesen" on public.firmenrechnung
  for select to authenticated
  using (true);

-- Anlegen nur über die Funktion unten (Nummer und Ersteller kommen vom Server)
create or replace function public.firmenrechnung_anlegen(p jsonb)
returns public.firmenrechnung
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nummer text;
  v_zeile public.firmenrechnung;
begin
  update public.rechnungsnummer_stand
  set letzte_nummer = letzte_nummer + 1
  where id = 1
  returning letzte_nummer::text into v_nummer;

  if v_nummer is null then
    raise exception 'Rechnungsnummer-Zähler fehlt (Tabelle rechnungsnummer_stand)';
  end if;

  insert into public.firmenrechnung (
    "Rechnungsnummer", "Rechnungsdatum", "Empfaenger", "Auftragsnummer",
    "Leistungsdatum", "Zeit", "Ort", "Ansprechpartner", "Aktivitaet",
    "Beschreibung", "Positionen", "Kilometer", "KmSatz", "MwStSatz",
    "Netto", "MwSt", "Brutto", "Bemerkung", erstellt_von
  ) values (
    v_nummer,
    coalesce(nullif(p ->> 'Rechnungsdatum', '')::date, current_date),
    p ->> 'Empfaenger',
    nullif(p ->> 'Auftragsnummer', ''),
    nullif(p ->> 'Leistungsdatum', '')::date,
    nullif(p ->> 'Zeit', ''),
    nullif(p ->> 'Ort', ''),
    nullif(p ->> 'Ansprechpartner', ''),
    nullif(p ->> 'Aktivitaet', ''),
    nullif(p ->> 'Beschreibung', ''),
    coalesce(p -> 'Positionen', '[]'::jsonb),
    coalesce((p ->> 'Kilometer')::numeric, 0),
    coalesce((p ->> 'KmSatz')::numeric, 0.30),
    coalesce((p ->> 'MwStSatz')::numeric, 19),
    coalesce((p ->> 'Netto')::numeric, 0),
    coalesce((p ->> 'MwSt')::numeric, 0),
    coalesce((p ->> 'Brutto')::numeric, 0),
    nullif(p ->> 'Bemerkung', ''),
    coalesce(nullif(auth.jwt() ->> 'email', ''), 'unbekannt')
  )
  returning * into v_zeile;

  return v_zeile;
end;
$$;

revoke all on function public.firmenrechnung_anlegen(jsonb) from public;
grant execute on function public.firmenrechnung_anlegen(jsonb) to authenticated;
