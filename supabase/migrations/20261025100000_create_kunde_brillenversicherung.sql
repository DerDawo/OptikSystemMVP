-- Brillenversicherungen in der Kundenkartei: die vermittelten Verträge eines
-- Versicherungspartners (Tarife BP100 bis BP800) je Kunde, getrennt von den
-- Aufträgen verwaltet. Der Kunde ist der Versicherungsnehmer; die
-- versicherte Person (z. B. das Kind) kann abweichen.
-- Pro Vertrag: Tarif, Vertragsbeginn, Vergütung, Status der Vergütung
-- (Ausstehend, Ausgezahlt, Storniert), Meldedatum und ob der Vertrag
-- abgetreten ist - wie in der Vergütungsübersicht des Partners.
-- Neue Tabelle, keine Änderung an bestehenden Daten.

create table if not exists public.kunde_brillenversicherung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint not null references public.kunde (id) on delete cascade,
  "VersichertePerson" text,
  "Tarif" text not null check (length(trim("Tarif")) > 0),
  "Vertragsnummer" text,
  "Vertragsbeginn" date,
  "Vertragsende" date,
  "Verguetung" numeric(10, 2) check ("Verguetung" is null or "Verguetung" >= 0),
  "Status" text not null default 'Ausstehend'
    check ("Status" in ('Ausstehend', 'Ausgezahlt', 'Storniert')),
  "Gemeldet" date not null default current_date,
  "Abgetreten" boolean not null default false,
  "Bemerkung" text,
  check (
    "Vertragsende" is null
    or "Vertragsbeginn" is null
    or "Vertragsende" >= "Vertragsbeginn"
  )
);

comment on table public.kunde_brillenversicherung is
  'Brillenversicherungen (vermittelte Verträge) je Kunde; Kunde = Versicherungsnehmer.';
comment on column public.kunde_brillenversicherung."VersichertePerson" is
  'Versicherte Person, wenn sie nicht der Kunde selbst ist (z. B. das Kind); leer = Kunde selbst.';
comment on column public.kunde_brillenversicherung."Tarif" is
  'Tarif des Partners, z. B. BP250, BP400, BP800.';
comment on column public.kunde_brillenversicherung."Verguetung" is
  'Vergütung (Provision) in Euro für diesen Vertrag.';
comment on column public.kunde_brillenversicherung."Status" is
  'Status der Vergütung: Ausstehend, Ausgezahlt oder Storniert.';
comment on column public.kunde_brillenversicherung."Gemeldet" is
  'Datum, an dem der Vertrag gemeldet wurde.';
comment on column public.kunde_brillenversicherung."Abgetreten" is
  'Vertrag ist abgetreten (Hinweis "abgetreten" in der Vergütungsübersicht).';

create index if not exists kunde_brillenversicherung_kunde_id_idx
  on public.kunde_brillenversicherung (kunde_id, "Vertragsbeginn" desc);
create index if not exists kunde_brillenversicherung_status_idx
  on public.kunde_brillenversicherung ("Status");

-- RLS wie bei den übrigen Tabellen: nur angemeldete Benutzer.
alter table public.kunde_brillenversicherung enable row level security;

drop policy if exists "Authenticated users can manage kunde_brillenversicherung"
  on public.kunde_brillenversicherung;
create policy "Authenticated users can manage kunde_brillenversicherung"
  on public.kunde_brillenversicherung
  for all
  to authenticated
  using (true)
  with check (true);
