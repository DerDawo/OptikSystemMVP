-- Online-Terminbuchung: Kunden fragen auf der öffentlichen Seite /buchen.html
-- (auf augenoptik-ulm.de eingebettet) einen freien Termin an. Die Anfrage
-- blockiert den Zeitraum, bis sie im Betrieb bestätigt (-> termin) oder
-- abgelehnt wird.
--
-- Die Tabellen bleiben wie alle anderen nur für angemeldete Benutzer
-- zugänglich. Die öffentliche Seite (Rolle anon) darf ausschließlich die
-- drei Funktionen buchung_konfiguration, buchung_freie_zeiten und
-- buchung_anfragen aufrufen; sie sehen keine Termine oder Kundendaten,
-- nur freie Uhrzeiten.

create table if not exists public.buchung_einstellung (
  id smallint primary key default 1 check (id = 1),
  -- aus, bis Öffnungszeiten und Terminarten eingetragen sind
  aktiv boolean not null default false,
  -- frühester Termin: jetzt + vorlauf_stunden
  vorlauf_stunden integer not null default 12 check (vorlauf_stunden between 0 and 336),
  -- spätester Termin: heute + tage_im_voraus
  tage_im_voraus integer not null default 42 check (tage_im_voraus between 1 and 365),
  -- Abstand der angebotenen Startzeiten
  raster_min integer not null default 15 check (raster_min between 5 and 120),
  -- kurzer Text oben auf der Buchungsseite
  hinweis text
);

insert into public.buchung_einstellung (id) values (1) on conflict (id) do nothing;

create table if not exists public.buchung_terminart (
  id bigint generated by default as identity primary key,
  name text not null unique,
  dauer_min integer not null check (dauer_min between 5 and 240),
  aktiv boolean not null default true,
  reihenfolge integer not null default 0
);

insert into public.buchung_terminart (name, dauer_min, reihenfolge) values
  ('Sehtest', 30, 1),
  ('Brillenberatung', 45, 2),
  ('Kontaktlinsen', 45, 3),
  ('Allgemeine Beratung Augenkrankheiten', 30, 4),
  ('Abholung / Service', 15, 5)
on conflict (name) do nothing;

-- Öffnungszeiten je Wochentag (1 = Montag … 7 = Sonntag nach ISO), mehrere
-- Zeilen je Tag für die Mittagspause
create table if not exists public.buchung_oeffnungszeit (
  id bigint generated by default as identity primary key,
  wochentag smallint not null check (wochentag between 1 and 7),
  von time not null,
  bis time not null,
  check (von < bis)
);

create table if not exists public.buchung_anfrage (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  terminart_id bigint references public.buchung_terminart (id) on delete set null,
  terminart text not null,
  "Start" timestamptz not null,
  "Ende" timestamptz not null,
  vorname text not null,
  nachname text not null,
  email text,
  telefon text,
  nachricht text,
  status text not null default 'offen'
    check (status in ('offen', 'bestaetigt', 'abgelehnt')),
  kunde_id bigint references public.kunde (id) on delete set null,
  termin_id bigint references public.termin (id) on delete set null,
  bearbeitet_am timestamptz,
  check ("Start" < "Ende")
);

create index if not exists buchung_anfrage_start_idx on public.buchung_anfrage ("Start");
create index if not exists buchung_anfrage_status_idx on public.buchung_anfrage (status);

comment on table public.buchung_anfrage is
  'Online-Terminanfragen von der öffentlichen Buchungsseite; offen = blockiert den Zeitraum, bis bestätigt (termin_id) oder abgelehnt';

-- RLS wie überall: nur angemeldete Benutzer
alter table public.buchung_einstellung enable row level security;
alter table public.buchung_terminart enable row level security;
alter table public.buchung_oeffnungszeit enable row level security;
alter table public.buchung_anfrage enable row level security;

drop policy if exists "Authenticated users can manage buchung_einstellung" on public.buchung_einstellung;
create policy "Authenticated users can manage buchung_einstellung" on public.buchung_einstellung
  for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users can manage buchung_terminart" on public.buchung_terminart;
create policy "Authenticated users can manage buchung_terminart" on public.buchung_terminart
  for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users can manage buchung_oeffnungszeit" on public.buchung_oeffnungszeit;
create policy "Authenticated users can manage buchung_oeffnungszeit" on public.buchung_oeffnungszeit
  for all to authenticated using (true) with check (true);
drop policy if exists "Authenticated users can manage buchung_anfrage" on public.buchung_anfrage;
create policy "Authenticated users can manage buchung_anfrage" on public.buchung_anfrage
  for all to authenticated using (true) with check (true);

-- Was die Buchungsseite anzeigt: an/aus, Hinweis, Firma, Terminarten
create or replace function public.buchung_konfiguration()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'aktiv', coalesce((select aktiv from buchung_einstellung where id = 1), false),
    'hinweis', (select hinweis from buchung_einstellung where id = 1),
    'firma', (select coalesce(nullif("Marke", ''), nullif("Firmenname", ''), "Name") from betrieb order by id limit 1),
    'telefon', (select "Telefon" from betrieb order by id limit 1),
    'terminarten', coalesce((
      select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'dauer_min', dauer_min) order by reihenfolge, name)
      from buchung_terminart where aktiv
    ), '[]'::jsonb)
  );
$$;

-- Freie Startzeiten für eine Terminart: innerhalb der Öffnungszeiten,
-- frühestens jetzt + Vorlauf, ohne Überschneidung mit Terminen (auch aus
-- Google) oder offenen Anfragen. Es gibt nur einen Platz gleichzeitig.
create or replace function public.buchung_freie_zeiten(p_terminart_id bigint)
returns table (start timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  with e as (
    select * from buchung_einstellung where id = 1 and aktiv
  ),
  t as (
    select make_interval(mins => dauer_min) as dauer
    from buchung_terminart where id = p_terminart_id and aktiv
  ),
  tage as (
    select d::date as tag
    from e, generate_series(
      (now() at time zone 'Europe/Berlin')::date,
      (now() at time zone 'Europe/Berlin')::date + e.tage_im_voraus,
      interval '1 day'
    ) d
  ),
  fenster as (
    select (tage.tag + o.von) at time zone 'Europe/Berlin' as von,
           (tage.tag + o.bis) at time zone 'Europe/Berlin' as bis
    from tage
    join buchung_oeffnungszeit o on o.wochentag = extract(isodow from tage.tag)
  ),
  slots as (
    select s as start, s + t.dauer as ende
    from fenster, t, e,
      generate_series(fenster.von, fenster.bis - t.dauer, make_interval(mins => e.raster_min)) s
  )
  select slots.start
  from slots, e
  where slots.start >= now() + make_interval(hours => e.vorlauf_stunden)
    and not exists (
      select 1 from termin x where x."Start" < slots.ende and x."Ende" > slots.start
    )
    and not exists (
      select 1 from buchung_anfrage a
      where a.status = 'offen' and a."Start" < slots.ende and a."Ende" > slots.start
    )
  order by slots.start;
$$;

-- Anfrage von der Buchungsseite. Fehler kommen als Klartext zurück
-- (raise exception), die Seite zeigt sie an.
create or replace function public.buchung_anfragen(
  p_terminart_id bigint,
  p_start timestamptz,
  p_vorname text,
  p_nachname text,
  p_email text,
  p_telefon text,
  p_nachricht text,
  p_einwilligung boolean
)
returns bigint
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_art buchung_terminart;
  v_email text := nullif(lower(btrim(coalesce(p_email, ''))), '');
  v_telefon text := nullif(btrim(coalesce(p_telefon, '')), '');
  v_vorname text := btrim(coalesce(p_vorname, ''));
  v_nachname text := btrim(coalesce(p_nachname, ''));
  v_id bigint;
begin
  if not coalesce(p_einwilligung, false) then
    raise exception 'Bitte stimmen Sie der Verarbeitung Ihrer Angaben zu.';
  end if;
  if v_vorname = '' or v_nachname = '' or length(v_vorname) > 80 or length(v_nachname) > 80 then
    raise exception 'Bitte geben Sie Vor- und Nachnamen an.';
  end if;
  if v_email is null and v_telefon is null then
    raise exception 'Bitte geben Sie eine E-Mail-Adresse oder Telefonnummer an.';
  end if;
  if v_email is not null and (length(v_email) > 200 or v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$') then
    raise exception 'Die E-Mail-Adresse ist ungültig.';
  end if;
  if v_telefon is not null and (length(v_telefon) > 40 or v_telefon !~ '^[0-9 +()/-]{5,}$') then
    raise exception 'Die Telefonnummer ist ungültig.';
  end if;
  if length(coalesce(p_nachricht, '')) > 1000 then
    raise exception 'Die Nachricht ist zu lang (höchstens 1000 Zeichen).';
  end if;

  -- nacheinander prüfen und eintragen, damit zwei Kunden nicht gleichzeitig
  -- denselben Termin bekommen
  perform pg_advisory_xact_lock(hashtext('buchung_anfrage'));

  -- Missbrauch bremsen: je Kontakt höchstens 3 offene Anfragen, insgesamt
  -- höchstens 30 neue Anfragen pro Stunde
  if (select count(*) from buchung_anfrage
      where status = 'offen'
        and ((v_email is not null and lower(email) = v_email)
          or (v_telefon is not null and telefon = v_telefon))) >= 3 then
    raise exception 'Sie haben bereits mehrere offene Anfragen. Wir melden uns bei Ihnen.';
  end if;
  if (select count(*) from buchung_anfrage where created_at > now() - interval '1 hour') >= 30 then
    raise exception 'Gerade sind sehr viele Anfragen eingegangen. Bitte rufen Sie uns an.';
  end if;

  select * into v_art from buchung_terminart where id = p_terminart_id and aktiv;
  if v_art.id is null then
    raise exception 'Diese Terminart kann nicht online gebucht werden.';
  end if;
  if not exists (select 1 from buchung_freie_zeiten(p_terminart_id) f where f.start = p_start) then
    raise exception 'Dieser Termin ist leider nicht mehr frei. Bitte wählen Sie eine andere Uhrzeit.';
  end if;

  insert into buchung_anfrage (terminart_id, terminart, "Start", "Ende", vorname, nachname, email, telefon, nachricht)
  values (v_art.id, v_art.name, p_start, p_start + make_interval(mins => v_art.dauer_min),
          v_vorname, v_nachname, v_email, v_telefon, nullif(btrim(coalesce(p_nachricht, '')), ''))
  returning id into v_id;
  return v_id;
end;
$$;

-- Bestätigen in UNICORN: Kunde (vorhanden oder neu) und Termin anlegen,
-- Anfrage abschließen - alles oder nichts. Nur für angemeldete Benutzer.
create or replace function public.buchung_bestaetigen(p_anfrage_id bigint, p_kunde_id bigint)
returns bigint
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
  v_a buchung_anfrage;
  v_kunde bigint := p_kunde_id;
  v_termin bigint;
begin
  select * into v_a from buchung_anfrage where id = p_anfrage_id for update;
  if v_a.id is null then
    raise exception 'Anfrage nicht gefunden.';
  end if;
  if v_a.status <> 'offen' then
    raise exception 'Die Anfrage ist bereits bearbeitet.';
  end if;
  if exists (select 1 from termin x where x."Start" < v_a."Ende" and x."Ende" > v_a."Start") then
    raise exception 'Zu dieser Zeit steht inzwischen schon ein Termin im Kalender.';
  end if;
  if v_kunde is null then
    insert into kunde ("Vorname", "Nachname", "Email", "Handy", "Kundenquelle", "Aufnahmedatum")
    values (v_a.vorname, v_a.nachname, v_a.email, v_a.telefon, 'Online-Terminbuchung', now())
    returning id into v_kunde;
  end if;
  insert into termin (kunde_id, "Start", "Ende", "Terminart", "Notiz")
  values (v_kunde, v_a."Start", v_a."Ende", v_a.terminart,
          concat_ws(E'\n', 'Online gebucht', v_a.nachricht))
  returning id into v_termin;
  update buchung_anfrage
  set status = 'bestaetigt', kunde_id = v_kunde, termin_id = v_termin, bearbeitet_am = now()
  where id = v_a.id;
  return v_termin;
end;
$$;

