-- OPTICA-Abrechnungen: ein Abrechnungslauf je Monat (Abrechnungsnachweis,
-- Gebührenrechnung, Kontoauszug, Umsatzstatistik), die Absetzungen der
-- Kostenträger, die elektronischen Kostenvoranschläge (eKV) und die
-- Original-PDFs im privaten Speicher "optica-abrechnung".
-- Die Rezepte selbst stehen weiter in kassenrezept (Belegnummer).
-- Nur neue Tabellen und ein neuer Speicher, keine Änderung an bestehenden Daten.

-- 1. Abrechnungsläufe ---------------------------------------------------------
create table if not exists public.optica_abrechnung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  "Abrechnungsmonat" text not null unique
    check ("Abrechnungsmonat" ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  "Abrechnungsdatum" date,
  "Rechnungsnummer" text,
  "Rechnungsdatum" date,
  "Brutto" numeric(10, 2) not null default 0,
  "Netto" numeric(10, 2) not null default 0,
  "MwSt" numeric(10, 2) not null default 0,
  "Zuzahlung" numeric(10, 2) not null default 0,
  "Forderung" numeric(10, 2) not null default 0,
  "Absetzungen" numeric(10, 2) not null default 0,
  "Gebuehren" numeric(10, 2) not null default 0,
  "GebuehrenRezepte" numeric(10, 2) not null default 0,
  "GebuehrenEkv" numeric(10, 2) not null default 0,
  "Zahlungen" numeric(10, 2) not null default 0,
  "AuszahlungMonat" numeric(10, 2) not null default 0,
  "SaldoVormonat" numeric(10, 2) not null default 0,
  "Auszahlung" numeric(10, 2) not null default 0,
  "RezepteEingesendet" integer,
  "RezepteAbgerechnet" integer,
  "RezepteZurueck" integer,
  "Steuersaetze" jsonb not null default '[]'::jsonb,
  "Kassenrechnungen" jsonb not null default '[]'::jsonb,
  "Umsatzstatistik" jsonb,
  "Dateien" jsonb not null default '[]'::jsonb,
  "Bemerkung" text
);

comment on table public.optica_abrechnung is
  'OPTICA-Abrechnungslauf je Abrechnungsmonat: Beträge aus Abrechnungsnachweis, Gebührenrechnung und Kontoauszug.';
comment on column public.optica_abrechnung."Abrechnungsmonat" is
  'Abrechnungsmonat im Format JJJJ-MM (OPTICA schreibt z. B. 9/2026-H).';
comment on column public.optica_abrechnung."Absetzungen" is
  'Ab-/Zusetzungen des laufenden Monats (negativ = zu Lasten des Betriebs).';
comment on column public.optica_abrechnung."Gebuehren" is
  'Gebühren brutto (positiv), die OPTICA mit der Auszahlung verrechnet.';
comment on column public.optica_abrechnung."SaldoVormonat" is
  'Kontosaldo Vormonat (Überzahlungen), negativ = Überzahlung wird verrechnet.';
comment on column public.optica_abrechnung."Auszahlung" is
  'Auszahlungsbetrag gesamt; negativ = Überzahlung (Betrieb schuldet OPTICA).';
comment on column public.optica_abrechnung."Steuersaetze" is
  'Netto/MwSt/Brutto je Steuersatz: [{"satz","netto","mwst","brutto"}].';
comment on column public.optica_abrechnung."Kassenrechnungen" is
  'Forderungsaufstellung aus dem Kontoauszug: [{"kassenart","kostentraeger","rechnungsnummer","anzahl","zuzahlung","netto"}].';
comment on column public.optica_abrechnung."Umsatzstatistik" is
  'Vergleichszahlen aus der Umsatzstatistik (Betrieb, Thüringen, Bund).';
comment on column public.optica_abrechnung."Dateien" is
  'Abgelegte Original-PDFs im Speicher optica-abrechnung: [{"name","pfad","art","groesse"}].';

-- 2. Absetzungen --------------------------------------------------------------
create table if not exists public.optica_absetzung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  abrechnung_id bigint not null
    references public.optica_abrechnung (id) on delete cascade,
  "Abrechnungsmonat" text not null,
  "Lfd" integer not null,
  "Kostentraeger" text,
  "Grund" text,
  "Rechnungsnummer" text,
  "Belegnummer" text,
  "MwStSatz" numeric(5, 2),
  "Betrag" numeric(10, 2) not null default 0,
  kassenrezept_id bigint references public.kassenrezept (id) on delete set null,
  kunde_id bigint references public.kunde (id) on delete set null,
  "Erledigt" boolean not null default false,
  "Notiz" text,
  unique (abrechnung_id, "Lfd")
);

comment on table public.optica_absetzung is
  'Absetzungen der Kostenträger aus dem OPTICA-Kontoauszug, eine Zeile je Posten.';
comment on column public.optica_absetzung."Belegnummer" is
  'Belegnummer des abgesetzten Rezepts; verknüpft über kassenrezept_id, wenn das Rezept bekannt ist.';
comment on column public.optica_absetzung."Erledigt" is
  'Vom Betrieb bearbeitet (z. B. Widerspruch eingelegt oder abgeschrieben).';

create index if not exists optica_absetzung_beleg_idx
  on public.optica_absetzung ("Belegnummer");
create index if not exists optica_absetzung_kassenrezept_idx
  on public.optica_absetzung (kassenrezept_id);
create index if not exists optica_absetzung_kunde_idx
  on public.optica_absetzung (kunde_id);

-- 3. Elektronische Kostenvoranschläge -----------------------------------------
create table if not exists public.optica_ekv (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  abrechnung_id bigint not null
    references public.optica_abrechnung (id) on delete cascade,
  "Abrechnungsmonat" text not null,
  "KvNummer" text not null,
  "Kasse" text,
  "KvDatum" date,
  "Genehmigt" date,
  "Genehmigungsnummer" text,
  "Teilgenehmigt" boolean not null default false,
  "Gebuehr" numeric(10, 2) not null default 0,
  "Zuzahlung" numeric(10, 2) not null default 0,
  "Beantragt" numeric(10, 2) not null default 0,
  "Erstattung" numeric(10, 2) not null default 0,
  "Versichertennummer" text,
  "Nachname" text,
  "Vorname" text,
  "Geburtsdatum" date,
  kunde_id bigint references public.kunde (id) on delete set null,
  unique (abrechnung_id, "KvNummer")
);

comment on table public.optica_ekv is
  'Elektronische Kostenvoranschläge (eKV) aus der OPTICA-eKV-Übersicht, eine Zeile je KV.';

create index if not exists optica_ekv_kunde_idx on public.optica_ekv (kunde_id);
create index if not exists optica_ekv_versnr_idx
  on public.optica_ekv ("Versichertennummer");

-- 4. Rechte wie bei kassenrezept: alle aktiven Rollen lesen, Inhaber und
--    Optiker bearbeiten. Änderungen ins Änderungsprotokoll.
do $$
declare
  t text;
  p record;
begin
  foreach t in array array['optica_abrechnung', 'optica_absetzung', 'optica_ekv'] loop
    for p in
      select policyname from pg_policies
      where schemaname = 'public' and tablename = t
    loop
      execute format('drop policy %I on public.%I', p.policyname, t);
    end loop;
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy rolle_lesen on public.%I for select to authenticated using (public.darf_lesen())', t);
    execute format(
      'create policy rolle_anlegen on public.%I for insert to authenticated with check (public.darf_bearbeiten())', t);
    execute format(
      'create policy rolle_aendern on public.%I for update to authenticated using (public.darf_bearbeiten()) with check (public.darf_bearbeiten())', t);
    execute format(
      'create policy rolle_loeschen on public.%I for delete to authenticated using (public.darf_bearbeiten())', t);
    execute format('drop trigger if exists aenderung_protokollieren on public.%I', t);
    execute format(
      'create trigger aenderung_protokollieren after insert or update or delete on public.%I for each row execute function public.protokolliere_aenderung()',
      t
    );
  end loop;
end;
$$;

-- 5. Privater Speicher für die Original-PDFs ----------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'optica-abrechnung',
  'optica-abrechnung',
  false,
  20971520, -- 20 MB
  array['application/pdf']
)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "optica_abrechnung_lesen" on storage.objects;
create policy "optica_abrechnung_lesen" on storage.objects
  for select to authenticated
  using (bucket_id = 'optica-abrechnung' and public.darf_lesen());

drop policy if exists "optica_abrechnung_hochladen" on storage.objects;
create policy "optica_abrechnung_hochladen" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'optica-abrechnung' and public.darf_bearbeiten());

drop policy if exists "optica_abrechnung_ersetzen" on storage.objects;
create policy "optica_abrechnung_ersetzen" on storage.objects
  for update to authenticated
  using (bucket_id = 'optica-abrechnung' and public.darf_bearbeiten())
  with check (bucket_id = 'optica-abrechnung' and public.darf_bearbeiten());

drop policy if exists "optica_abrechnung_loeschen" on storage.objects;
create policy "optica_abrechnung_loeschen" on storage.objects
  for delete to authenticated
  using (bucket_id = 'optica-abrechnung' and public.darf_bearbeiten());
