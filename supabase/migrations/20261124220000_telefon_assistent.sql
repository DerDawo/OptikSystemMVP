-- Rufnummer vergleichbar machen: nur Ziffern, +49/0049 -> 0
create or replace function public.telefon_normalisieren(p_nummer text)
returns text
language sql
immutable
set search_path = public
as $$
  select nullif(
    regexp_replace(
      regexp_replace(
        regexp_replace(coalesce(p_nummer, ''), '[^0-9+]', '', 'g'),
        '^(\+|00)49', '0'),
      '[^0-9]', '', 'g'),
    '');
$$;

-- Kunde zur Rufnummer (nur intern, für die Zuordnung im Anrufprotokoll)
create or replace function public.telefon_kunde_zur_nummer(p_nummer text)
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select k.id
  from kunde k
  where public.telefon_normalisieren(p_nummer) is not null
    and length(public.telefon_normalisieren(p_nummer)) >= 6
    and public.telefon_normalisieren(p_nummer) in (
      public.telefon_normalisieren(k."Handy"),
      public.telefon_normalisieren(k."TelefonnummerPrivat"),
      public.telefon_normalisieren(k."TelefonnummerGeschaeftlich"))
  order by k.id desc
  limit 1;
$$;

-- Öffnungsstatus jetzt (Europe/Berlin) aus den Öffnungszeiten der
-- Online-Buchung, als Satz zum Vorlesen plus Wochenübersicht
create or replace function public.telefon_oeffnungsstatus()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_jetzt timestamp := now() at time zone 'Europe/Berlin';
  v_tag date := v_jetzt::date;
  v_zeit time := v_jetzt::time;
  v_namen text[] := array['Montag','Dienstag','Mittwoch','Donnerstag','Freitag','Samstag','Sonntag'];
  v_offen_bis time;
  v_n_tag date;
  v_n_von time;
  v_text text;
  v_woche text;
begin
  if not exists (select 1 from buchung_oeffnungszeit) then
    return jsonb_build_object('offen', null, 'text', 'Öffnungszeiten sind nicht hinterlegt.', 'woche', '');
  end if;

  select o.bis into v_offen_bis
  from buchung_oeffnungszeit o
  where o.wochentag = extract(isodow from v_tag) and o.von <= v_zeit and o.bis > v_zeit
  order by o.bis desc limit 1;

  -- nächste Öffnung (heute später oder an einem der nächsten 7 Tage)
  select d.tag, o.von into v_n_tag, v_n_von
  from generate_series(0, 7) i
  cross join lateral (select v_tag + i as tag) d
  join buchung_oeffnungszeit o on o.wochentag = extract(isodow from d.tag)
  where d.tag > v_tag or o.von > v_zeit
  order by d.tag, o.von
  limit 1;

  if v_offen_bis is not null then
    v_text := 'Wir haben gerade geöffnet, heute bis ' || to_char(v_offen_bis, 'FMHH24:MI') || ' Uhr.';
  elsif v_n_tag is null then
    v_text := 'Wir haben gerade geschlossen.';
  elsif v_n_tag = v_tag then
    v_text := 'Wir haben gerade geschlossen und öffnen heute wieder um ' || to_char(v_n_von, 'FMHH24:MI') || ' Uhr.';
  elsif v_n_tag = v_tag + 1 then
    v_text := 'Wir haben gerade geschlossen und öffnen morgen um ' || to_char(v_n_von, 'FMHH24:MI') || ' Uhr.';
  else
    v_text := 'Wir haben gerade geschlossen und öffnen am ' || v_namen[extract(isodow from v_n_tag)::int]
      || ' um ' || to_char(v_n_von, 'FMHH24:MI') || ' Uhr.';
  end if;

  select string_agg(t.zeile, '; ' order by t.wochentag) into v_woche
  from (
    select o.wochentag,
      v_namen[o.wochentag] || ' ' || string_agg(
        to_char(o.von, 'FMHH24:MI') || '–' || to_char(o.bis, 'FMHH24:MI'), ' und ' order by o.von) as zeile
    from buchung_oeffnungszeit o
    group by o.wochentag
  ) t;

  return jsonb_build_object(
    'offen', v_offen_bis is not null,
    'text', v_text,
    'woche', coalesce(v_woche, '') || '. An den übrigen Tagen geschlossen.'
  );
end;
$$;

-- Wissen nachschlagen: Volltextsuche, jedes Wort zählt (ODER), beste 3
create or replace function public.telefon_wissen_suchen(p_frage text)
returns table (frage text, antwort text)
language sql
stable
security definer
set search_path = public
as $$
  with q as (
    select to_tsquery('german', string_agg(w, ' | ')) as abfrage
    from regexp_split_to_table(lower(coalesce(p_frage, '')), '[^[:alnum:]äöüß]+') w
    where length(w) >= 3
  )
  select w.frage, w.antwort
  from telefon_wissen w, q
  where w.aktiv and q.abfrage is not null and w.suchtext @@ q.abfrage
  order by ts_rank(w.suchtext, q.abfrage) desc
  limit 3;
$$;

-- Auftragsstatus: nur bei passendem Nachnamen UND Geburtsdatum. Je
-- Rufnummer höchstens 3 Fehlversuche am Tag, insgesamt 20 pro Stunde.
create or replace function public.telefon_auftragsstatus(
  p_nachname text,
  p_geburtsdatum date,
  p_anrufer text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_nummer text := public.telefon_normalisieren(p_anrufer);
  v_kunden bigint[];
  v_kunde kunde;
  v_heute date := (now() at time zone 'Europe/Berlin')::date;
  v_auftraege jsonb;
begin
  if (select count(*) from telefon_pruefung
      where not erfolgreich and created_at > now() - interval '1 day'
        and anrufer_nummer is not distinct from v_nummer) >= 3
     or (select count(*) from telefon_pruefung
         where not erfolgreich and created_at > now() - interval '1 hour') >= 20 then
    return jsonb_build_object('gefunden', false, 'gesperrt', true,
      'hinweis', 'Zu viele Versuche. Bitte einen Rückruf anbieten.');
  end if;

  select array_agg(k.id order by k.id desc) into v_kunden
  from kunde k
  where lower(btrim(k."Nachname")) = lower(btrim(coalesce(p_nachname, '')))
    and k."Geburtsdatum"::date = p_geburtsdatum;

  if v_kunden is null then
    insert into telefon_pruefung (anrufer_nummer, erfolgreich) values (v_nummer, false);
    return jsonb_build_object('gefunden', false,
      'hinweis', 'Kein Kunde mit diesem Namen und Geburtsdatum. Einmal nachfragen, sonst Rückruf anbieten.');
  end if;

  -- mehrere Treffer: den nehmen, dessen Rufnummer passt, sonst Rückruf
  if array_length(v_kunden, 1) > 1 then
    select * into v_kunde from kunde
    where id = any (v_kunden) and id = public.telefon_kunde_zur_nummer(p_anrufer);
    if v_kunde.id is null then
      insert into telefon_pruefung (anrufer_nummer, erfolgreich) values (v_nummer, true);
      return jsonb_build_object('gefunden', false, 'mehrdeutig', true,
        'hinweis', 'Mehrere Kunden passen. Bitte einen Rückruf anbieten.');
    end if;
  else
    select * into v_kunde from kunde where id = v_kunden[1];
  end if;

  insert into telefon_pruefung (anrufer_nummer, erfolgreich) values (v_nummer, true);

  -- Brillenaufträge der letzten 12 Monate, ohne reine Dienstleistungen,
  -- abgeholte nur, wenn die Abholung höchstens 14 Tage her ist
  select coalesce(jsonb_agg(jsonb_build_object(
      'art', coalesce(nullif(btrim(b."BrillenArt"), ''), 'Brille'),
      'auftragsdatum', to_char(b."Datum"::date, 'DD.MM.YYYY'),
      'stand', case
        when b."Abholung"::date <= v_heute then 'abgeholt am ' || to_char(b."Abholung"::date, 'DD.MM.YYYY')
        when b."Abholung" is not null or b."Fertig" is not null then 'fertig, liegt zur Abholung bereit'
        when b."Bestellt" is not null then 'beim Hersteller bestellt am ' || to_char(b."Bestellt"::date, 'DD.MM.YYYY') || ', noch nicht fertig'
        else 'in Bearbeitung, noch nicht bestellt'
      end
    ) order by b."Datum" desc nulls last), '[]'::jsonb)
  into v_auftraege
  from brille b
  where b.kunde_id = v_kunde.id
    and coalesce(b."Datum"::date, v_heute) > v_heute - 365
    and coalesce(b."BrillenArt", '') !~* '(seh(ü|ue)berpr(ü|ue)fung|sehtest|refraktion|beratung|gutschein|gutachten|gesundheitstag|kontaktlinse|^cl\M)'
    and (b."Abholung" is null or b."Abholung"::date > v_heute - 14);

  return jsonb_build_object(
    'gefunden', true,
    'kunde_id', v_kunde.id,
    'anrede', btrim(concat_ws(' ', nullif(btrim(v_kunde."Anrede"::text), ''), v_kunde."Nachname")),
    'auftraege', v_auftraege,
    'hinweis', case when v_auftraege = '[]'::jsonb
      then 'Kein offener Brillenauftrag. Für Kontaktlinsen oder Fragen zur Rechnung Rückruf anbieten.'
      else 'Nur den Stand nennen, keine Preise oder Gesundheitsdaten.' end
  );
end;
$$;

