-- Telefon-Assistent (KI-Sprachagent bei ElevenLabs): nimmt Anrufe an, wenn im
-- Laden besetzt ist oder niemand abnimmt.
--
-- Der Agent spricht nie direkt mit der Datenbank. Er ruft die Edge Function
-- telefon-agent auf (gesichert mit einem eigenen Schlüssel), und nur sie
-- benutzt die Funktionen unten (Rolle service_role). Termine laufen über die
-- vorhandene Online-Buchung (buchung_freie_zeiten / buchung_anfragen) und
-- erscheinen wie Website-Anfragen unter „Online-Anfragen“.
--
-- Tabellen:
--   telefon_anruf          ein Eintrag je Gespräch (Zusammenfassung, Rückrufbitte)
--   telefon_wissen         Fragen und Antworten, die der Agent nachschlagen kann
--   telefon_wissensluecke  Fragen, die der Agent nicht beantworten konnte
--   telefon_pruefung       Versuche, sich für den Auftragsstatus auszuweisen

create table if not exists public.telefon_anruf (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  conversation_id text not null unique,
  anrufer_nummer text,
  kunde_id bigint references public.kunde (id) on delete set null,
  dauer_sek integer,
  zusammenfassung text,
  -- Gesprächsverlauf [{role, message, time_in_call_secs}]
  transkript jsonb,
  -- termin | rueckruf | auskunft | notfall | abgebrochen
  ergebnis text,
  buchung_anfrage_id bigint references public.buchung_anfrage (id) on delete set null,
  rueckruf_erbeten boolean not null default false,
  rueckruf_name text,
  rueckruf_nummer text,
  rueckruf_anliegen text,
  dringend boolean not null default false,
  auftrag_auskunft boolean not null default false,
  erledigt_am timestamptz,
  erledigt_von text
);

create index if not exists telefon_anruf_created_idx on public.telefon_anruf (created_at desc);
create index if not exists telefon_anruf_offen_idx on public.telefon_anruf (created_at desc)
  where rueckruf_erbeten and erledigt_am is null;
create index if not exists telefon_anruf_kunde_idx on public.telefon_anruf (kunde_id);
create index if not exists telefon_anruf_anfrage_idx on public.telefon_anruf (buchung_anfrage_id);

comment on table public.telefon_anruf is
  'Telefon-Assistent: ein Eintrag je Gespräch, angelegt vom Agenten (Rückrufbitte) bzw. nach dem Anruf (Zusammenfassung, Verlauf).';

create table if not exists public.telefon_wissen (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  frage text not null check (length(frage) between 3 and 500),
  antwort text not null check (length(antwort) between 1 and 2000),
  aktiv boolean not null default true,
  suchtext tsvector generated always as (
    to_tsvector('german', coalesce(frage, '') || ' ' || coalesce(antwort, ''))
  ) stored
);

create index if not exists telefon_wissen_suche_idx on public.telefon_wissen using gin (suchtext);

comment on table public.telefon_wissen is
  'Telefon-Assistent: Fragen und Antworten (z. B. Parken, Zahlung, Kassenzuschuss), die der Agent im Gespräch nachschlägt.';

create table if not exists public.telefon_wissensluecke (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  conversation_id text,
  frage text not null check (length(frage) between 3 and 500),
  status text not null default 'offen' check (status in ('offen', 'beantwortet', 'verworfen')),
  wissen_id bigint references public.telefon_wissen (id) on delete set null,
  bearbeitet_am timestamptz
);

create index if not exists telefon_wissensluecke_offen_idx on public.telefon_wissensluecke (created_at desc)
  where status = 'offen';
create index if not exists telefon_wissensluecke_wissen_idx on public.telefon_wissensluecke (wissen_id);

comment on table public.telefon_wissensluecke is
  'Telefon-Assistent: Fragen, die der Agent nicht beantworten konnte. Eine Antwort im System wird zu telefon_wissen (Lernschleife).';

create table if not exists public.telefon_pruefung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  anrufer_nummer text,
  erfolgreich boolean not null
);

create index if not exists telefon_pruefung_idx on public.telefon_pruefung (anrufer_nummer, created_at desc);

