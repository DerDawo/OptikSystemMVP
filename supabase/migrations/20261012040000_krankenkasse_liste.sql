-- Liste der gesetzlichen Krankenkassen als Auswahl für Kunden
-- (Kundenkartei "Kasse", Kunde bearbeiten). Quelle: Krankenkassenliste des
-- GKV-Spitzenverbands, Stand 02.01.2026 (92 Kassen).
-- "IK" (Institutionskennzeichen = Kassen-Nr.) ist anfangs leer und kann unter
-- Stammdaten > Krankenkassen eingetragen werden; bei der Auswahl einer Kasse
-- wird es dann als Kassen-Nr. übernommen. Freie Eingabe bleibt möglich
-- (private Kassen, ältere Namen aus Prisma) - Kundendaten ändern sich nicht.

create table if not exists public.krankenkasse (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Name" text not null unique,
  "Kassenart" text,
  "Geoeffnet" text,
  "IK" text,
  "Aktiv" boolean not null default true
);

comment on table public.krankenkasse is
  'Gesetzliche Krankenkassen für die Auswahl beim Kunden (GKV-Spitzenverband, Stand 02.01.2026).';
comment on column public.krankenkasse."Geoeffnet" is
  'Geöffnet für (Bundesländer, bundesweit oder betriebsbezogen).';
comment on column public.krankenkasse."IK" is
  'Institutionskennzeichen; wird bei Auswahl als Kassen-Nr. des Kunden übernommen.';
comment on column public.krankenkasse."Aktiv" is
  'In der Auswahl angeboten.';

alter table public.krankenkasse enable row level security;

drop policy if exists "Authenticated users can manage krankenkasse" on public.krankenkasse;
create policy "Authenticated users can manage krankenkasse" on public.krankenkasse
  for all
  to authenticated
  using (true)
  with check (true);

