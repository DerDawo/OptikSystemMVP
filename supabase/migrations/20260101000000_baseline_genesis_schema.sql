create table if not exists public.zusatzleistung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Bezeichnung" text,
  "Betrag" numeric
);
comment on table public.zusatzleistung is 'Zusatzleistungen im Zusamenahng mit Brillen';

create table if not exists public.brille (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Berater" varchar,
  "Refraktion" varchar,
  "Datum" timestamptz,
  "Werkstatt" varchar,
  "Abholung" timestamptz,
  "Notizen" text,
  "GlasLinks" bigint references public.glass(id),
  "GlasRechts" bigint references public.glass(id),
  "Fassung" bigint references public.fassung(id),
  "Glastyp" bigint references public.glastyp(id),
  "RabattBezeichnung" varchar,
  "Summe" numeric,
  "BrillenArt" text,
  kunde_id bigint references public.kunde(id)
);
comment on table public.brille is 'Alle Brillen von allen Kunden';

create table if not exists public.brille_hat_zusatzleistungen (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  brille_id bigint references public.brille(id),
  zusatzleistung_id bigint references public.zusatzleistung(id)
);

create table if not exists public.kunde_leistet_zauzahlung_fuer_brille (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "KundenID" bigint references public.kunde(id),
  "BrillenID" bigint references public.brille(id),
  "Datum" timestamp,
  "Betrag" numeric,
  "Restbetrag" numeric
);
comment on table public.kunde_leistet_zauzahlung_fuer_brille is 'Alle Zuzahlungen, die ein Kunde für eine Brille geleistet hat';
