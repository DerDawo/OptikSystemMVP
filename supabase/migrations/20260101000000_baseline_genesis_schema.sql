-- Baseline-Schema aus der Zeit vor Einführung der Migrationsverwaltung.
--
-- kunde, brille, glass, glastyp, fassung, zusatzleistung,
-- brille_hat_zusatzleistungen und kunde_leistet_zauzahlung_fuer_brille wurden
-- ursprünglich über den Supabase Studio Table Editor angelegt, bevor
-- `supabase/migrations/` genutzt wurde (siehe Kommentar in
-- 20260830235900_fix_brille_hat_zusatzleistungen_column_casing.sql). Es gab
-- dafür bislang keine eingecheckte Migration, wodurch ein frisches Supabase-
-- Projekt (z. B. ein neuer Dev-/Prod-Branch oder -Projekt) nicht allein aus
-- `supabase/migrations/` aufgebaut werden konnte - alle nachfolgenden
-- Migrationen setzen diese Tabellen bereits voraus.
--
-- Diese Migration rekonstruiert den Stand dieser Tabellen so, wie er beim
-- allerersten Lauf von 20260828000000_restrict_access_to_authenticated_users.sql
-- vorlag (per Introspektion des laufenden Projekts ermittelt). Sie muss vor
-- allen anderen Migrationen laufen (Zeitstempel entsprechend früh gewählt).
--
-- "BrillenArt" (brille) und "Bezeichnung" (zusatzleistung) waren ursprünglich
-- eigene Enum-Typen, die von 20260830130000_add_brillenart_stammdaten.sql
-- bzw. 20260830120000_zusatzleistung_kategorie_und_rabatt.sql per
-- `alter column ... type text` + `drop type if exists ...` auf text
-- umgestellt wurden. Da beide Migrationen `drop type if exists` verwenden,
-- werden die Spalten hier direkt als text angelegt (funktional identisch,
-- ohne die längst entfernten Enum-Typen erneut anzulegen).
--
-- Bewusst durchgängig idempotent (`create table if not exists`, Typen nur
-- anlegen falls nicht vorhanden): So kann diese Migration auch gegen das
-- bestehende Dev-Projekt angewendet werden, in dem diese Tabellen bereits
-- existieren (sie ist dort dann ein No-Op, wird aber in der
-- Migrationshistorie erfasst) - nur so bleibt `supabase/migrations/`
-- projektübergreifend als vollständige, alleinige Quelle nutzbar.

do $$
begin
  if not exists (select 1 from pg_type where typname = 'anrede' and typnamespace = 'public'::regnamespace) then
    create type public.anrede as enum ('Frau', 'Herr', 'Prof.', 'Prof. Dr.', 'Dr.');
  end if;
  if not exists (select 1 from pg_type where typname = 'krankenversicherung' and typnamespace = 'public'::regnamespace) then
    create type public.krankenversicherung as enum ('Privat Krankenversichert', 'Gesetzlich Krankenversichert', 'Unbekannt');
  end if;
  if not exists (select 1 from pg_type where typname = 'seite' and typnamespace = 'public'::regnamespace) then
    create type public.seite as enum ('Links', 'Rechts');
  end if;
end $$;

create table if not exists public.kunde (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "KundenNummer" varchar,
  "Aufnahmedatum" timestamptz,
  "Anrede" public.anrede not null,
  "Nachname" varchar,
  "Vorname" varchar,
  "Geburtsdatum" timestamp,
  "Geschlecht" varchar,
  "Straße" varchar,
  "Tätigkeit" varchar,
  "TelefonnummerPrivat" varchar,
  "Email" varchar,
  "KrankenkassenNummer" varchar,
  "VersichertenNummer" varchar,
  "Postleitzahl" varchar,
  "Hausnummer" varchar,
  "Stadt" varchar,
  "TelefonnummerGeschaeftlich" varchar,
  "KrankenversicherungsTyp" public.krankenversicherung,
  last_viewed_at timestamptz default (now() - interval '8 days')
);
comment on table public.kunde is 'Alle Kunden von Robert Ulm';

