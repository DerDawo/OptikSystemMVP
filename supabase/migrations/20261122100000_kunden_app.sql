-- Nachricht, Absage-Wunsch oder Rechnungskopie anfordern
create or replace function public.portal_nachricht_senden(
  p_sitzung text,
  p_text text,
  p_art text default 'nachricht',
  p_termin_id bigint default null,
  p_bezug text default null
)
returns bigint
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_kunde bigint := portal_kunde(p_sitzung);
  v_text text := btrim(coalesce(p_text, ''));
  v_id bigint;
begin
  if p_art not in ('nachricht', 'absage', 'rechnung') then
    raise exception 'Unbekannte Art der Nachricht.';
  end if;
  if v_text = '' then
    raise exception 'Bitte schreiben Sie eine Nachricht.';
  end if;
  if length(v_text) > 2000 then
    raise exception 'Die Nachricht ist zu lang (höchstens 2000 Zeichen).';
  end if;
  if (select count(*) from portal_nachricht
      where kunde_id = v_kunde and von_kunde and created_at > now() - interval '1 day') >= 20 then
    raise exception 'Sie haben heute schon viele Nachrichten geschickt. Bitte rufen Sie uns an.';
  end if;
  if p_termin_id is not null and not exists (
    select 1 from termin where id = p_termin_id and kunde_id = v_kunde
  ) then
    raise exception 'Termin nicht gefunden.';
  end if;
  if p_art = 'absage' and p_termin_id is null then
    raise exception 'Termin fehlt.';
  end if;
  insert into portal_nachricht (kunde_id, von_kunde, art, text, termin_id, bezug)
  values (v_kunde, true, p_art, v_text, p_termin_id, left(nullif(btrim(coalesce(p_bezug, '')), ''), 200))
  returning id into v_id;
  return v_id;
end;
$$;

-- Einwilligungen und bevorzugten Kontaktweg selbst ändern; die Änderung
-- steht zusätzlich als Nachricht beim Kunden (Nachweis mit Zeitpunkt)
create or replace function public.portal_einwilligung_setzen(
  p_sitzung text,
  p_werbung boolean,
  p_kanaele text[],
  p_kontaktweg text
)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_kunde bigint := portal_kunde(p_sitzung);
  v_kanaele text[];
  v_fuer text;
  v_weg text := nullif(btrim(coalesce(p_kontaktweg, '')), '');
begin
  select coalesce(array_agg(k order by array_position(array['E-Mail', 'SMS', 'WhatsApp', 'Post'], k)), '{}')
  into v_kanaele
  from (select distinct unnest(coalesce(p_kanaele, '{}')) k) x
  where k in ('E-Mail', 'SMS', 'WhatsApp', 'Post');
  if v_weg is not null and v_weg not in ('SMS', 'WhatsApp', 'eMail', 'Telefon') then
    raise exception 'Unbekannter Kontaktweg.';
  end if;
  v_fuer := case when coalesce(p_werbung, false) and cardinality(v_kanaele) > 0
    then 'Angebote per ' || array_to_string(v_kanaele, ', ') || ' (Kunden-App)' end;
  update kunde
  set "Werbeeinwilligung" = coalesce(p_werbung, false) and cardinality(v_kanaele) > 0,
      "WerbeeinwilligungFuer" = v_fuer,
      "Kontaktweg" = v_weg
  where id = v_kunde;
  insert into portal_nachricht (kunde_id, von_kunde, art, text, erledigt_am, erledigt_von)
  values (v_kunde, true, 'einwilligung',
    'Einwilligung in der Kunden-App geändert: Angebote und Neuigkeiten '
      || case when v_fuer is null then 'abgelehnt' else 'erlaubt per ' || array_to_string(v_kanaele, ', ') end
      || '; bevorzugter Kontaktweg: ' || coalesce(v_weg, 'keiner'),
    now(), 'Kunden-App');
end;
$$;

-- Termin anfragen: wie die öffentliche Buchung, aber schon dem Kunden
-- zugeordnet
create or replace function public.portal_termin_anfragen(
  p_sitzung text,
  p_terminart_id bigint,
  p_start timestamptz,
  p_nachricht text
)
returns bigint
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_kunde bigint := portal_kunde(p_sitzung);
  v_k kunde;
  v_art buchung_terminart;
  v_id bigint;
begin
  if length(coalesce(p_nachricht, '')) > 1000 then
    raise exception 'Die Nachricht ist zu lang (höchstens 1000 Zeichen).';
  end if;
  perform pg_advisory_xact_lock(hashtext('buchung_anfrage'));
  if (select count(*) from buchung_anfrage where kunde_id = v_kunde and status = 'offen') >= 3 then
    raise exception 'Sie haben bereits mehrere offene Anfragen. Wir melden uns bei Ihnen.';
  end if;
  select * into v_art from buchung_terminart where id = p_terminart_id and aktiv;
  if v_art.id is null then
    raise exception 'Diese Terminart kann nicht online gebucht werden.';
  end if;
  if not exists (select 1 from buchung_freie_zeiten(p_terminart_id) f where f.start = p_start) then
    raise exception 'Dieser Termin ist leider nicht mehr frei. Bitte wählen Sie eine andere Uhrzeit.';
  end if;
  select * into v_k from kunde where id = v_kunde;
  insert into buchung_anfrage (terminart_id, terminart, "Start", "Ende", vorname, nachname,
                               email, telefon, nachricht, kunde_id)
  values (v_art.id, v_art.name, p_start, p_start + make_interval(mins => v_art.dauer_min),
          coalesce(nullif(btrim(v_k."Vorname"), ''), '-'), coalesce(nullif(btrim(v_k."Nachname"), ''), '-'),
          nullif(lower(btrim(coalesce(v_k."Email", ''))), ''),
          coalesce(nullif(btrim(coalesce(v_k."Handy", '')), ''), nullif(btrim(coalesce(v_k."TelefonnummerPrivat", '')), '')),
          concat_ws(E'\n', 'Aus der Kunden-App', nullif(btrim(coalesce(p_nachricht, '')), '')),
          v_kunde)
  returning id into v_id;
  return v_id;
end;
$$;

