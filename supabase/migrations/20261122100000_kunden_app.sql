-- Kunden-App (kunde.html): Kunden sehen ihre Termine, Brillenpass,
-- Auftragsstatus und Rechnungen, schreiben dem Laden und verwalten ihre
-- Einwilligungen.
--
-- Sicherheit: Kunden bekommen KEINEN Supabase-Login. Ein Login gilt in
-- UNICORN ohne Eintrag in benutzer_rolle als Optiker und dürfte damit alles
-- lesen. Stattdessen:
--   1. Der Laden erstellt in der Karteikarte eine Einladung
--      (portal_einladen). Der Link enthält einen langen Zufallsschlüssel; in
--      der Datenbank steht nur dessen SHA-256-Wert.
--   2. Beim ersten Öffnen bestätigt der Kunde sein Geburtsdatum
--      (portal_anmelden). Nach 5 Fehlversuchen ist die Einladung eine Stunde
--      gesperrt. Ergebnis ist ein Sitzungsschlüssel (90 Tage gültig).
--   3. Die App (Rolle anon) ruft ausschließlich die Funktionen portal_* mit
--      dem Sitzungsschlüssel auf. Sie liefern nur Daten dieses einen Kunden
--      und nur ausgewählte Felder (keine Notizen, Diagnosen, internen
--      Vermerke). Die Tabellen selbst sind für anon gesperrt.
--
-- Keine Änderung an bestehenden Daten.

-- 1. Tabellen ----------------------------------------------------------------

create table if not exists public.portal_zugang (
  id bigint generated by default as identity primary key,
  kunde_id bigint not null references public.kunde (id) on delete cascade,
  schluessel_hash text not null unique,
  erstellt_am timestamptz not null default now(),
  erstellt_von text,
  gueltig_bis timestamptz not null default now() + interval '1 year',
  widerrufen_am timestamptz,
  fehlversuche integer not null default 0,
  gesperrt_bis timestamptz,
  zuletzt_genutzt timestamptz
);

create index if not exists portal_zugang_kunde_idx on public.portal_zugang (kunde_id);

comment on table public.portal_zugang is
  'Kunden-App: Einladung je Kunde (nur Hash des Link-Schlüssels). Eine neue Einladung widerruft die alte.';

create table if not exists public.portal_sitzung (
  id bigint generated by default as identity primary key,
  zugang_id bigint not null references public.portal_zugang (id) on delete cascade,
  schluessel_hash text not null unique,
  erstellt_am timestamptz not null default now(),
  gueltig_bis timestamptz not null default now() + interval '90 days',
  zuletzt_genutzt timestamptz
);

create index if not exists portal_sitzung_zugang_idx on public.portal_sitzung (zugang_id);

comment on table public.portal_sitzung is
  'Kunden-App: angemeldetes Gerät (nur Hash des Sitzungsschlüssels).';

create table if not exists public.portal_nachricht (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint not null references public.kunde (id) on delete cascade,
  -- true = vom Kunden aus der App, false = Antwort des Ladens
  von_kunde boolean not null default true,
  art text not null default 'nachricht'
    check (art in ('nachricht', 'absage', 'rechnung', 'einwilligung', 'antwort')),
  text text not null check (length(text) between 1 and 2000),
  termin_id bigint references public.termin (id) on delete set null,
  bezug text,
  erledigt_am timestamptz,
  erledigt_von text
);

create index if not exists portal_nachricht_kunde_idx on public.portal_nachricht (kunde_id, created_at desc);
create index if not exists portal_nachricht_offen_idx on public.portal_nachricht (created_at desc)
  where von_kunde and erledigt_am is null;

comment on table public.portal_nachricht is
  'Kunden-App: Nachrichten zwischen Kunde und Laden (auch Absage-Wünsche, Rechnungskopien, Einwilligungsänderungen).';

alter table public.portal_zugang enable row level security;
alter table public.portal_sitzung enable row level security;
alter table public.portal_nachricht enable row level security;

-- Zugänge und Sitzungen: keine Regeln -> nur über die Funktionen unten
revoke all on public.portal_zugang from anon, authenticated;
revoke all on public.portal_sitzung from anon, authenticated;

-- Nachrichten: Mitarbeiter lesen und bearbeiten (wie "nachrichten"/"kunde"
-- auch die Aushilfe), anon nie
revoke all on public.portal_nachricht from anon;
drop policy if exists "Mitarbeiter lesen portal_nachricht" on public.portal_nachricht;
create policy "Mitarbeiter lesen portal_nachricht" on public.portal_nachricht
  for select to authenticated using (public.darf_lesen());
drop policy if exists "Mitarbeiter schreiben portal_nachricht" on public.portal_nachricht;
create policy "Mitarbeiter schreiben portal_nachricht" on public.portal_nachricht
  for insert to authenticated with check (public.darf_lesen() and not von_kunde);
drop policy if exists "Mitarbeiter erledigen portal_nachricht" on public.portal_nachricht;
create policy "Mitarbeiter erledigen portal_nachricht" on public.portal_nachricht
  for update to authenticated using (public.darf_lesen()) with check (public.darf_lesen());
drop policy if exists "Bearbeiter löschen portal_nachricht" on public.portal_nachricht;
create policy "Bearbeiter löschen portal_nachricht" on public.portal_nachricht
  for delete to authenticated using (public.darf_bearbeiten());

-- 2. Hilfsfunktionen (nicht von außen aufrufbar) ------------------------------

create or replace function public.portal_hash(p_schluessel text)
returns text
language sql
immutable
set search_path = public
as $$
  select encode(sha256(convert_to(coalesce(p_schluessel, ''), 'UTF8')), 'hex');
$$;

create or replace function public.portal_neuer_schluessel()
returns text
language sql
volatile
set search_path = public
as $$
  -- zwei UUIDv4 = 244 Zufallsbits
  select replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
$$;

-- Kunde zur Sitzung; Fehler, wenn abgelaufen, widerrufen oder unbekannt
create or replace function public.portal_kunde(p_sitzung text)
returns bigint
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_kunde bigint;
  v_sitzung bigint;
begin
  select z.kunde_id, s.id into v_kunde, v_sitzung
  from portal_sitzung s
  join portal_zugang z on z.id = s.zugang_id
  where s.schluessel_hash = portal_hash(p_sitzung)
    and s.gueltig_bis > now()
    and z.widerrufen_am is null
    and z.gueltig_bis > now();
  if v_kunde is null then
    raise exception 'Bitte melden Sie sich erneut an.' using errcode = '28000';
  end if;
  update portal_sitzung set zuletzt_genutzt = now()
  where id = v_sitzung and (zuletzt_genutzt is null or zuletzt_genutzt < now() - interval '5 minutes');
  return v_kunde;
end;
$$;

revoke all on function public.portal_hash(text) from public, anon, authenticated;
revoke all on function public.portal_neuer_schluessel() from public, anon, authenticated;
revoke all on function public.portal_kunde(text) from public, anon, authenticated;

-- 3. Funktionen für UNICORN (Mitarbeiter) -------------------------------------

-- Neue Einladung: widerruft frühere, liefert den Schlüssel für den Link
-- (nur dieses eine Mal im Klartext)
create or replace function public.portal_einladen(p_kunde_id bigint)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_schluessel text := portal_neuer_schluessel();
  v_gueltig timestamptz;
begin
  if not public.darf_lesen() then
    raise exception 'Keine Berechtigung.';
  end if;
  if not exists (select 1 from kunde where id = p_kunde_id) then
    raise exception 'Kunde nicht gefunden.';
  end if;
  if (select "Geburtsdatum" from kunde where id = p_kunde_id) is null then
    raise exception 'Bitte zuerst das Geburtsdatum eintragen. Der Kunde bestätigt damit seine Anmeldung.';
  end if;
  update portal_zugang set widerrufen_am = now()
  where kunde_id = p_kunde_id and widerrufen_am is null;
  insert into portal_zugang (kunde_id, schluessel_hash, erstellt_von)
  values (p_kunde_id, portal_hash(v_schluessel), nullif(auth.jwt() ->> 'email', ''))
  returning gueltig_bis into v_gueltig;
  return jsonb_build_object('schluessel', v_schluessel, 'gueltig_bis', v_gueltig);
end;
$$;

create or replace function public.portal_zugang_status(p_kunde_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v portal_zugang;
begin
  if not public.darf_lesen() then
    raise exception 'Keine Berechtigung.';
  end if;
  select * into v from portal_zugang
  where kunde_id = p_kunde_id and widerrufen_am is null and gueltig_bis > now()
  order by erstellt_am desc limit 1;
  if v.id is null then
    return jsonb_build_object('aktiv', false);
  end if;
  return jsonb_build_object(
    'aktiv', true,
    'erstellt_am', v.erstellt_am,
    'gueltig_bis', v.gueltig_bis,
    'gesperrt_bis', case when v.gesperrt_bis > now() then v.gesperrt_bis end,
    'angemeldet', exists (select 1 from portal_sitzung s where s.zugang_id = v.id and s.gueltig_bis > now()),
    'zuletzt_genutzt', greatest(v.zuletzt_genutzt,
      (select max(s.zuletzt_genutzt) from portal_sitzung s where s.zugang_id = v.id))
  );
end;
$$;

create or replace function public.portal_widerrufen(p_kunde_id bigint)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
begin
  if not public.darf_lesen() then
    raise exception 'Keine Berechtigung.';
  end if;
  update portal_zugang set widerrufen_am = now()
  where kunde_id = p_kunde_id and widerrufen_am is null;
end;
$$;

revoke all on function public.portal_einladen(bigint) from public, anon;
revoke all on function public.portal_zugang_status(bigint) from public, anon;
revoke all on function public.portal_widerrufen(bigint) from public, anon;
grant execute on function public.portal_einladen(bigint) to authenticated;
grant execute on function public.portal_zugang_status(bigint) to authenticated;
grant execute on function public.portal_widerrufen(bigint) to authenticated;

-- 4. Funktionen für die Kunden-App (anon) -------------------------------------

-- Einladung + Geburtsdatum -> Sitzungsschlüssel
create or replace function public.portal_anmelden(p_einladung text, p_geburtsdatum date)
returns text
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v portal_zugang;
  v_geb date;
  v_schluessel text;
begin
  select * into v from portal_zugang
  where schluessel_hash = portal_hash(p_einladung)
  for update;
  if v.id is null or v.widerrufen_am is not null or v.gueltig_bis <= now() then
    raise exception 'Dieser Link ist nicht mehr gültig. Bitte fragen Sie im Laden nach einem neuen Link.';
  end if;
  if v.gesperrt_bis > now() then
    raise exception 'Zu viele Fehlversuche. Bitte versuchen Sie es in einer Stunde noch einmal oder rufen Sie uns an.';
  end if;
  select "Geburtsdatum"::date into v_geb from kunde where id = v.kunde_id;
  if v_geb is null or p_geburtsdatum is null or v_geb <> p_geburtsdatum then
    -- Fehlversuch zählen; die Sperre muss trotz Fehlermeldung bestehen
    -- bleiben, deshalb kein raise nach dem update (würde zurückrollen),
    -- sondern Rückgabe null
    update portal_zugang
    set fehlversuche = fehlversuche + 1,
        gesperrt_bis = case when fehlversuche + 1 >= 5 then now() + interval '1 hour' end
    where id = v.id;
    return null;
  end if;
  update portal_zugang set fehlversuche = 0, gesperrt_bis = null, zuletzt_genutzt = now()
  where id = v.id;
  -- alte, abgelaufene Sitzungen aufräumen
  delete from portal_sitzung where zugang_id = v.id and gueltig_bis <= now();
  v_schluessel := portal_neuer_schluessel();
  insert into portal_sitzung (zugang_id, schluessel_hash) values (v.id, portal_hash(v_schluessel));
  return v_schluessel;
end;
$$;

create or replace function public.portal_abmelden(p_sitzung text)
returns void
language sql
volatile
security definer
set search_path = public
as $$
  delete from portal_sitzung where schluessel_hash = portal_hash(p_sitzung);
$$;

