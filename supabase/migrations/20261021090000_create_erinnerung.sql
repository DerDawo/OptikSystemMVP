-- Erinnerungen im Dashboard ("Heute zu tun"): freie Merkzettel wie
-- "Bruchrezept anfertigen", optional mit Fälligkeitsdatum und Kunde.
-- Erledigte Erinnerungen bleiben mit Zeitpunkt in "Erledigt" erhalten.
-- Neue Tabelle, keine Änderung an bestehenden Daten.

create table if not exists public.erinnerung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Text" text not null check (length(trim("Text")) > 0),
  "Faellig" date,
  "Erledigt" timestamptz,
  kunde_id bigint references public.kunde (id) on delete set null
);

comment on table public.erinnerung is
  'Erinnerungen für "Heute zu tun" im Dashboard (z.B. Bruchrezept anfertigen).';
comment on column public.erinnerung."Faellig" is
  'Optionales Fälligkeitsdatum; ohne Datum gilt die Erinnerung sofort.';
comment on column public.erinnerung."Erledigt" is
  'Zeitpunkt, zu dem die Erinnerung abgehakt wurde; leer = offen.';

create index if not exists erinnerung_offen_idx
  on public.erinnerung ("Faellig") where "Erledigt" is null;
create index if not exists erinnerung_kunde_id_idx
  on public.erinnerung (kunde_id);

-- RLS wie bei den übrigen Tabellen: nur angemeldete Benutzer.
alter table public.erinnerung enable row level security;

drop policy if exists "Authenticated users can manage erinnerung" on public.erinnerung;
create policy "Authenticated users can manage erinnerung" on public.erinnerung
  for all
  to authenticated
  using (true)
  with check (true);
