-- Fundusberichte als strukturierte Einträge: zentrales Fundusarchiv und
-- Verlauf je Kunde. Bilder und PDF bleiben getrennt in kunde_dokument, hier
-- steht der freigegebene Befund mit Verweis auf die verwendeten Originale.
-- Ein freigegebener Bericht wird nicht geändert: nur Lesen und Anlegen.
-- Neue Tabelle, keine Änderung an bestehenden Daten.

create table if not exists public.fundusbericht (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint not null references public.kunde (id) on delete cascade,
  "Untersuchung" timestamptz not null,
  "Untersucher" text not null check (length(trim("Untersucher")) > 0),
  "Methode" text,
  "Geraet" text,
  "Bild_OS" bigint references public.kunde_dokument (id) on delete set null,
  "Bild_OD" bigint references public.kunde_dokument (id) on delete set null,
  "Bericht" bigint references public.kunde_dokument (id) on delete set null,
  "Befund" jsonb not null,
  "Seitenvergleich" text,
  "Gesamtbeurteilung" text,
  "Empfehlung" text,
  freigegeben_von text
);

comment on table public.fundusbericht is
  'Freigegebene Fundusbefunde (zentrales Archiv). Original-Aufnahmen und PDF liegen in kunde_dokument.';
comment on column public.fundusbericht."Befund" is
  'Je Auge (OS, OD): qualitaet und bereiche mit status und text.';
comment on column public.fundusbericht.freigegeben_von is
  'E-Mail-Adresse des angemeldeten Benutzers; wird vom Trigger gesetzt und nicht vom Client.';

create index if not exists fundusbericht_kunde_id_idx
  on public.fundusbericht (kunde_id, "Untersuchung" desc);
create index if not exists fundusbericht_untersuchung_idx
  on public.fundusbericht ("Untersuchung" desc);

create or replace function public.fundusbericht_freigabe_setzen()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.freigegeben_von :=
    coalesce(nullif(auth.jwt() ->> 'email', ''), 'unbekannt');
  return new;
end;
$$;

drop trigger if exists fundusbericht_freigabe on public.fundusbericht;
create trigger fundusbericht_freigabe
  before insert on public.fundusbericht
  for each row execute function public.fundusbericht_freigabe_setzen();

alter table public.fundusbericht enable row level security;

drop policy if exists "fundusbericht_lesen" on public.fundusbericht;
create policy "fundusbericht_lesen" on public.fundusbericht
  for select to authenticated
  using (true);

drop policy if exists "fundusbericht_anlegen" on public.fundusbericht;
create policy "fundusbericht_anlegen" on public.fundusbericht
  for insert to authenticated
  with check (true);
