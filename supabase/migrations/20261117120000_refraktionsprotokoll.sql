-- Refraktionsprotokoll (wie in Prisma): je Kunde objektive und subjektive
-- Refraktionen, Messungen nach MKH, nc-Tonometrie und medizinische
-- Sachverhalte, unabhängig von einem Brillenauftrag. Werte je Auge in
-- Spalten mit Endung Rechts/Links. Grundlage für spätere Verlaufsansichten.
-- Neue Tabelle, keine Änderung an bestehenden Daten.

create table if not exists public.refraktion (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint not null references public.kunde (id) on delete cascade,
  "Art" text not null check (
    "Art" in ('Objektiv', 'Subjektiv', 'Subjektiv MKH', 'Tonometrie', 'Medizinisches')
  ),
  "Zeitpunkt" timestamptz not null default now(),
  "Untersucher" text,
  "Geraet" text,
  "Messabstand" text,
  "VisBino" numeric,
  "Kreuztest" text,
  "Zeigertest" text,
  "Doppelzeigertest" text,
  "Hakentest" text,
  "Stereotest" text,
  "Valenztest" text,
  "Anamnese" text,
  "Notizen" text,
  "SphRechts" numeric,
  "CylRechts" numeric,
  "ARechts" numeric,
  "AddRechts" numeric,
  "PrismaRechts" numeric,
  "BasisRechts" numeric,
  "VisSCRechts" numeric,
  "VisCCRechts" numeric,
  "PDRechts" numeric,
  "HSARechts" numeric,
  "IODRechts" numeric,
  "PachymetrieRechts" numeric,
  "SphLinks" numeric,
  "CylLinks" numeric,
  "ALinks" numeric,
  "AddLinks" numeric,
  "PrismaLinks" numeric,
  "BasisLinks" numeric,
  "VisSCLinks" numeric,
  "VisCCLinks" numeric,
  "PDLinks" numeric,
  "HSALinks" numeric,
  "IODLinks" numeric,
  "PachymetrieLinks" numeric
);

comment on table public.refraktion is
  'Refraktionsprotokoll: objektive/subjektive Refraktion, MKH, Tonometrie, Medizinisches je Kunde; Werte je Auge mit Endung Rechts/Links.';

create index if not exists refraktion_kunde_idx
  on public.refraktion (kunde_id, "Zeitpunkt" desc);

alter table public.refraktion enable row level security;

drop policy if exists rolle_lesen on public.refraktion;
create policy rolle_lesen on public.refraktion
  for select to authenticated using (public.darf_lesen());
drop policy if exists rolle_anlegen on public.refraktion;
create policy rolle_anlegen on public.refraktion
  for insert to authenticated with check (public.darf_bearbeiten());
drop policy if exists rolle_aendern on public.refraktion;
create policy rolle_aendern on public.refraktion
  for update to authenticated
  using (public.darf_bearbeiten()) with check (public.darf_bearbeiten());
drop policy if exists rolle_loeschen on public.refraktion;
create policy rolle_loeschen on public.refraktion
  for delete to authenticated using (public.darf_bearbeiten());

drop trigger if exists aenderung_protokollieren on public.refraktion;
create trigger aenderung_protokollieren
  after insert or update or delete on public.refraktion
  for each row execute function public.protokolliere_aenderung();
