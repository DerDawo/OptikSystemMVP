-- Abgerechnete Kassenrezepte (Sammelabrechnung über den Abrechnungsdienstleister,
-- "Rezeptübersicht" pro Abrechnungsmonat). Eine Zeile je abgerechnetem Rezept.
-- Dient dem Gesamtüberblick ("Abgerechnete Rezepte") und dem Bereich
-- "Abgerechnete Rezepte" in der Kundenkartei.
-- Der Kunde wird über kunde_id verknüpft; ist der Kunde (noch) nicht
-- zugeordnet, bleiben Name, Geburtsdatum und Versichertennummer aus dem Beleg
-- erhalten. Neue Tabelle, keine Änderung an bestehenden Daten.

create table if not exists public.kassenrezept (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint references public.kunde (id) on delete set null,
  "Abrechnungsmonat" text not null
    check ("Abrechnungsmonat" ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  "Abrechnungsdatum" date,
  "Belegnummer" text not null unique,
  "Nachname" text,
  "Vorname" text,
  "Geburtsdatum" date,
  "Versichertennummer" text,
  "Krankenkasse" text,
  "Rezeptdatum" date,
  "Leistungen" jsonb not null default '[]'::jsonb,
  "Netto" numeric(10, 2) not null default 0,
  "MwSt" numeric(10, 2) not null default 0,
  "Brutto" numeric(10, 2) not null default 0,
  "Zuzahlung" numeric(10, 2) not null default 0 check ("Zuzahlung" >= 0),
  "Bemerkung" text
);

comment on table public.kassenrezept is
  'Abgerechnete Kassenrezepte aus der Sammelabrechnung (Rezeptübersicht), eine Zeile je Rezept.';
comment on column public.kassenrezept."Abrechnungsmonat" is
  'Abrechnungsmonat im Format JJJJ-MM, z. B. 2026-03.';
comment on column public.kassenrezept."Belegnummer" is
  'Belegnummer des Rezepts aus der Rezeptübersicht (eindeutig).';
comment on column public.kassenrezept."Leistungen" is
  'Positionen des Rezepts als JSON-Liste: [{"pzn","text","faktor","netto","brutto","zuzahlung","mwst"}].';
comment on column public.kassenrezept."Brutto" is
  'Rechnungsbetrag inklusive Zuzahlung des Versicherten.';
comment on column public.kassenrezept."Zuzahlung" is
  'Gesetzliche Zuzahlung des Versicherten; Kassenanteil = Brutto - Zuzahlung.';

create index if not exists kassenrezept_kunde_id_idx
  on public.kassenrezept (kunde_id, "Rezeptdatum" desc);
create index if not exists kassenrezept_abrechnungsmonat_idx
  on public.kassenrezept ("Abrechnungsmonat");
create index if not exists kassenrezept_versichertennummer_idx
  on public.kassenrezept ("Versichertennummer");

-- RLS wie bei den übrigen Tabellen: nur angemeldete Benutzer.
alter table public.kassenrezept enable row level security;

drop policy if exists "Authenticated users can manage kassenrezept"
  on public.kassenrezept;
create policy "Authenticated users can manage kassenrezept"
  on public.kassenrezept
  for all
  to authenticated
  using (true)
  with check (true);
