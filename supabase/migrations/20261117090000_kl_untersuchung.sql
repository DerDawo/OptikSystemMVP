-- Kontrollen und Topometrie zur CL-Kartei (wie in Prisma im Baum links unter
-- der CL-Kartei): je Eintrag Art "Kontrolle" (Tragezeit, Beschwerden, Visus
-- mit Linse, Überrefraktion, Sitz, Beweglichkeit, Spaltlampe, Linsenzustand,
-- Ergebnis, nächste Kontrolle) oder "Topometrie" (Hornhautradien und
-- -achsen, Exzentrizität, HH-Durchmesser, Pupille, Lidspalte, Gerät).
-- Werte je Auge in Spalten mit Endung Rechts/Links. Neue Tabelle, keine
-- Änderung an bestehenden Daten.

create table if not exists public.kl_untersuchung (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint references public.kunde (id) on delete cascade,
  kontaktlinse_id bigint not null references public.kontaktlinse (id) on delete cascade,
  "Art" text not null check ("Art" in ('Kontrolle', 'Topometrie')),
  "Datum" date not null default current_date,
  "Untersucher" text,
  "Tragezeit" text,
  "Beschwerden" text,
  "Ergebnis" text,
  "NaechsteKontrolle" date,
  "Geraet" text,
  "Notizen" text,
  "VisCLRechts" numeric,
  "UeberSphRechts" numeric,
  "UeberCylRechts" numeric,
  "UeberARechts" numeric,
  "RadiusFlachRechts" numeric,
  "AchseFlachRechts" numeric,
  "RadiusSteilRechts" numeric,
  "AchseSteilRechts" numeric,
  "ExzentrizitaetRechts" numeric,
  "HHDurchmesserRechts" numeric,
  "PupilleRechts" numeric,
  "LidspalteRechts" numeric,
  "SitzRechts" text,
  "BeweglichkeitRechts" text,
  "FluobildRechts" text,
  "BindehautRechts" text,
  "HornhautRechts" text,
  "LinsenzustandRechts" text,
  "VisCLLinks" numeric,
  "UeberSphLinks" numeric,
  "UeberCylLinks" numeric,
  "UeberALinks" numeric,
  "RadiusFlachLinks" numeric,
  "AchseFlachLinks" numeric,
  "RadiusSteilLinks" numeric,
  "AchseSteilLinks" numeric,
  "ExzentrizitaetLinks" numeric,
  "HHDurchmesserLinks" numeric,
  "PupilleLinks" numeric,
  "LidspalteLinks" numeric,
  "SitzLinks" text,
  "BeweglichkeitLinks" text,
  "FluobildLinks" text,
  "BindehautLinks" text,
  "HornhautLinks" text,
  "LinsenzustandLinks" text
);

comment on table public.kl_untersuchung is
  'Kontrollen und Topometrie zu einer CL-Kartei (kontaktlinse), Werte je Auge mit Endung Rechts/Links.';

create index if not exists kl_untersuchung_kontaktlinse_idx
  on public.kl_untersuchung (kontaktlinse_id, "Datum" desc);
create index if not exists kl_untersuchung_kunde_idx
  on public.kl_untersuchung (kunde_id);

-- Rollen wie die übrigen Fachdaten: lesen alle aktiven Rollen, bearbeiten
-- Inhaber und Optiker (siehe 20261116090000_rollen_und_protokoll.sql)
alter table public.kl_untersuchung enable row level security;

drop policy if exists rolle_lesen on public.kl_untersuchung;
create policy rolle_lesen on public.kl_untersuchung
  for select to authenticated using (public.darf_lesen());
drop policy if exists rolle_anlegen on public.kl_untersuchung;
create policy rolle_anlegen on public.kl_untersuchung
  for insert to authenticated with check (public.darf_bearbeiten());
drop policy if exists rolle_aendern on public.kl_untersuchung;
create policy rolle_aendern on public.kl_untersuchung
  for update to authenticated
  using (public.darf_bearbeiten()) with check (public.darf_bearbeiten());
drop policy if exists rolle_loeschen on public.kl_untersuchung;
create policy rolle_loeschen on public.kl_untersuchung
  for delete to authenticated using (public.darf_bearbeiten());

-- Änderungsprotokoll
drop trigger if exists aenderung_protokollieren on public.kl_untersuchung;
create trigger aenderung_protokollieren
  after insert or update or delete on public.kl_untersuchung
  for each row execute function public.protokolliere_aenderung();
