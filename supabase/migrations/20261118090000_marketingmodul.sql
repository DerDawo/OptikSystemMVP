-- Marketingmodul (wie in Prisma): Kundenauswahl mit beliebig vielen
-- Bedingungen (UND/ODER), gespeicherte Selektionen, Aktionen mit den
-- angeschriebenen Kunden und eine Erfolgsanalyse (wer hat danach gekauft?).
-- Neue Ansicht und zwei neue Tabellen, keine Änderung an bestehenden Daten.

-- Je Kunde die Merkmale für die Auswahl. security_invoker: es gelten die
-- RLS-Regeln der Tabellen für den angemeldeten Benutzer.
create or replace view public.kunde_marketing
with (security_invoker = true) as
with brillen as (
  select
    kunde_id,
    max("Datum")::date as letzte_brille,
    count(*)::int as anzahl,
    coalesce(sum("Summe"), 0) as umsatz,
    bool_or("BrillenArt" ilike '%gleitsicht%') as gleitsicht
  from public.brille
  where kunde_id is not null
  group by kunde_id
),
linsen as (
  select
    kunde_id,
    max("Datum") as letzte_linse,
    coalesce(sum("Summe"), 0) as umsatz
  from public.kontaktlinse
  where kunde_id is not null
  group by kunde_id
)
select
  k.id,
  k."KundenNummer",
  k."Anrede"::text as "Anrede",
  k."Vorname",
  k."Nachname",
  k."Straße",
  k."Hausnummer",
  k."Postleitzahl",
  k."Stadt",
  k."Email",
  k."Handy",
  k."TelefonnummerPrivat",
  k."Werbeeinwilligung",
  k."Geburtsdatum"::date as "Geburtsdatum",
  extract(month from k."Geburtsdatum")::int as "Geburtsmonat",
  date_part('year', age(current_date, k."Geburtsdatum"::date))::int as "Alter",
  coalesce(k."Aufnahmedatum", k.created_at)::date as "KundeSeit",
  k."Krankenkasse",
  k."KrankenversicherungsTyp"::text as "Versicherung",
  k."Kundenquelle",
  k."Merkmal1",
  k."Merkmal2",
  k."Merkmal3",
  k."Merkmal4",
  b.letzte_brille as "LetzteBrille",
  coalesce(b.anzahl, 0) as "AnzahlBrillen",
  coalesce(b.gleitsicht, false) as "Gleitsicht",
  (l.kunde_id is not null) as "Kontaktlinsen",
  l.letzte_linse as "LetzteKontaktlinse",
  greatest(b.letzte_brille, l.letzte_linse) as "LetzterKauf",
  coalesce(b.umsatz, 0) + coalesce(l.umsatz, 0) as "Umsatz"
from public.kunde k
left join brillen b on b.kunde_id = k.id
left join linsen l on l.kunde_id = k.id;

comment on view public.kunde_marketing is
  'Marketingmodul: Merkmale je Kunde für die Kundenauswahl (Alter, Wohnort, letzte Brille, Umsatz ...).';

revoke all on public.kunde_marketing from anon;
grant select on public.kunde_marketing to authenticated;

-- Gespeicherte Kundenauswahl
create table if not exists public.marketing_selektion (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Name" text not null,
  "Verknuepfung" text not null default 'und'
    check ("Verknuepfung" in ('und', 'oder')),
  "Kriterien" jsonb not null default '[]'::jsonb,
  "Kanal" text not null default 'post'
    check ("Kanal" in ('post', 'email', 'handy', 'alle')),
  "NurEinwilligung" boolean not null default true,
  "Notizen" text
);

comment on table public.marketing_selektion is
  'Marketingmodul: gespeicherte Kundenauswahl (Bedingungen als JSON, UND/ODER-Verknüpfung).';

-- Durchgeführte Aktion (Mailing, Brief ...) mit den angeschriebenen Kunden
create table if not exists public.marketing_aktion (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Name" text not null,
  "Datum" date not null default current_date,
  "Kanal" text,
  selektion_id bigint references public.marketing_selektion (id)
    on delete set null,
  "Kriterien" jsonb,
  "KundenIds" bigint[] not null default '{}',
  "Kosten" numeric,
  "Notizen" text
);

comment on table public.marketing_aktion is
  'Marketingmodul: durchgeführte Aktion mit den angeschriebenen Kunden, Grundlage der Erfolgsanalyse.';

create index if not exists marketing_aktion_datum_idx
  on public.marketing_aktion ("Datum");

