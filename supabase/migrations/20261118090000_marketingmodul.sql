-- Erfolgsanalyse: wie viele der angeschriebenen Kunden haben innerhalb von
-- p_wochen Wochen nach der Aktion eine Brille oder Kontaktlinsen gekauft
-- (oder einen anderen Auftrag wie einen Sehtest erteilt), mit Umsatz.
-- security invoker: liest nur, was der Benutzer ohnehin sehen darf.
create or replace function public.marketing_erfolg(
  p_aktion bigint,
  p_wochen int default 8
)
returns table (
  angeschrieben int,
  kaeufer int,
  auftraege int,
  umsatz numeric
)
language sql
stable
security invoker
set search_path = public
as $$
  with a as (
    select "KundenIds" as ids,
           "Datum"::timestamp as von,
           "Datum"::timestamp + make_interval(weeks => greatest(p_wochen, 1)) as bis
    from public.marketing_aktion
    where id = p_aktion
  ),
  k as (select distinct unnest(ids) as kid from a),
  kauf as (
    select b.kunde_id, coalesce(b."Summe", 0) as summe
    from public.brille b, a
    where b.kunde_id in (select kid from k)
      and b."Datum" >= a.von and b."Datum" < a.bis
    union all
    select c.kunde_id, coalesce(c."Summe", 0)
    from public.kontaktlinse c, a
    where c.kunde_id in (select kid from k)
      and c."Datum" >= a.von and c."Datum" < a.bis
  )
  select
    (select count(*) from k)::int,
    (select count(distinct kunde_id) from kauf)::int,
    (select count(*) from kauf)::int,
    (select coalesce(sum(summe), 0) from kauf);
$$;

revoke all on function public.marketing_erfolg(bigint, int) from public, anon;
grant execute on function public.marketing_erfolg(bigint, int) to authenticated;
