-- Schuldnerliste (offene Posten) für das Dashboard, nur für den Inhaber.
-- Die Sichtbarkeit wird serverseitig erzwungen: nur wer in `inhaber_zugang`
-- eingetragen ist (E-Mail des Logins), darf die Tabelle lesen oder ändern.
-- Der Eintrag selbst steht NICHT im Repository, sondern wird einmalig per
-- SQL im Supabase-Editor angelegt (siehe Import-Skript). Neue Tabellen,
-- keine Änderung an bestehenden Daten.

create table if not exists public.inhaber_zugang (
  email text primary key
);

alter table public.inhaber_zugang enable row level security;

-- Jeder angemeldete Benutzer sieht höchstens seine eigene Zeile; Schreiben
-- ist über die App nicht möglich (nur im SQL-Editor).
drop policy if exists "Inhaber sieht eigenen Zugang" on public.inhaber_zugang;
create policy "Inhaber sieht eigenen Zugang"
  on public.inhaber_zugang
  for select
  to authenticated
  using (lower(email) = lower(coalesce(auth.jwt() ->> 'email', '')));

create or replace function public.ist_inhaber()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.inhaber_zugang
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.ist_inhaber() from public;
grant execute on function public.ist_inhaber() to authenticated;

create table if not exists public.schuldnerliste (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint references public.kunde (id) on delete set null,
  "Datum" date,
  "Kunde" text not null,
  "Ort" text,
  "Beleg" text,
  "AuftragsNr" text,
  "KundenNr" text,
  "Zahlart" text,
  "Offen" numeric(10, 2) not null default 0,
  "Bemerkung" text,
  "BezahltAm" date
);

comment on table public.schuldnerliste is
  'Offene Posten (Schuldnerliste), nur für den Inhaber sichtbar (RLS über ist_inhaber()).';
comment on column public.schuldnerliste."BezahltAm" is
  'Gesetzt, sobald der Posten bezahlt ist; bezahlte Posten erscheinen nicht mehr im Dashboard.';

create index if not exists schuldnerliste_offen_idx
  on public.schuldnerliste ("Datum")
  where "BezahltAm" is null;
create index if not exists schuldnerliste_kunde_id_idx
  on public.schuldnerliste (kunde_id);

alter table public.schuldnerliste enable row level security;

drop policy if exists "Nur Inhaber verwaltet Schuldnerliste"
  on public.schuldnerliste;
create policy "Nur Inhaber verwaltet Schuldnerliste"
  on public.schuldnerliste
  for all
  to authenticated
  using (public.ist_inhaber())
  with check (public.ist_inhaber());
