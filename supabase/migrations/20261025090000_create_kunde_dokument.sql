-- Dokumente in der Kundenkartei: Befunde, Fundusaufnahmen, Rezepte,
-- Arztbriefe, Kostenzusagen, Formulare u. a. als PDF oder Bild beim Kunden
-- ablegen.
--
-- Die Dateien liegen in einem PRIVATEN Storage-Bucket (keine öffentlichen
-- Links, Zugriff nur über kurzlebige signierte URLs) und sind nur für
-- angemeldete Benutzer les- und schreibbar. Die Tabelle kunde_dokument hält
-- die Metadaten (Kunde, Name, Art, Datum, hochgeladen von).
-- Neue Tabelle und neuer Bucket, keine Änderung an bestehenden Daten.

-- 1. Privater Bucket (idempotent; bei erneutem Lauf werden die Grenzen
--    wieder auf diese Werte gesetzt und der Bucket bleibt privat)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'kunde-dokumente',
  'kunde-dokumente',
  false,
  26214400, -- 25 MB
  array['application/pdf', 'image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- 2. Zugriff auf die Dateien: nur angemeldete Benutzer, nur dieser Bucket
drop policy if exists "kunde_dokumente_lesen" on storage.objects;
create policy "kunde_dokumente_lesen" on storage.objects
  for select to authenticated
  using (bucket_id = 'kunde-dokumente');

drop policy if exists "kunde_dokumente_hochladen" on storage.objects;
create policy "kunde_dokumente_hochladen" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'kunde-dokumente');

drop policy if exists "kunde_dokumente_loeschen" on storage.objects;
create policy "kunde_dokumente_loeschen" on storage.objects
  for delete to authenticated
  using (bucket_id = 'kunde-dokumente');

-- 3. Metadaten
create table if not exists public.kunde_dokument (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint not null references public.kunde (id) on delete cascade,
  "Name" text not null check (length(trim("Name")) > 0),
  "Art" text not null default 'Sonstiges' check ("Art" in (
    'Befund',
    'Fundusaufnahme',
    'Rezept',
    'Arztbrief',
    'Kostenzusage',
    'Formular',
    'Sonstiges'
  )),
  "Datum" date not null default current_date,
  "Pfad" text not null unique check (length(trim("Pfad")) > 0),
  "Typ" text,
  "Groesse" bigint check ("Groesse" is null or "Groesse" >= 0),
  hochgeladen_von text
);

comment on table public.kunde_dokument is
  'Metadaten der Dokumente in der Kundenkartei; die Datei liegt im privaten Bucket kunde-dokumente unter "Pfad".';
comment on column public.kunde_dokument."Art" is
  'Befund, Fundusaufnahme, Rezept, Arztbrief, Kostenzusage, Formular oder Sonstiges.';
comment on column public.kunde_dokument."Datum" is
  'Datum des Dokuments bzw. der Untersuchung (Vorbelegung: Tag des Hochladens).';
comment on column public.kunde_dokument."Pfad" is
  'Objektname im Bucket kunde-dokumente: <kunde_id>/<zufall>-<dateiname>.';
comment on column public.kunde_dokument.hochgeladen_von is
  'E-Mail-Adresse des angemeldeten Benutzers; wird vom Trigger gesetzt und nicht vom Client.';

create index if not exists kunde_dokument_kunde_id_idx
  on public.kunde_dokument (kunde_id, "Datum" desc);

-- 4. "hochgeladen von" kommt immer aus der Anmeldung, nie aus dem Client.
--    Beim Ändern bleiben Kunde, Datei und Uploader unveränderlich.
create or replace function public.kunde_dokument_schuetzen()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.hochgeladen_von :=
      coalesce(nullif(auth.jwt() ->> 'email', ''), 'unbekannt');
  else
    new.kunde_id := old.kunde_id;
    new."Pfad" := old."Pfad";
    new.hochgeladen_von := old.hochgeladen_von;
    new.created_at := old.created_at;
  end if;
  return new;
end;
$$;

drop trigger if exists kunde_dokument_schuetzen on public.kunde_dokument;
create trigger kunde_dokument_schuetzen
  before insert or update on public.kunde_dokument
  for each row execute function public.kunde_dokument_schuetzen();

-- 5. RLS wie bei den übrigen Tabellen: nur angemeldete Benutzer.
alter table public.kunde_dokument enable row level security;

drop policy if exists "Authenticated users can manage kunde_dokument" on public.kunde_dokument;
create policy "Authenticated users can manage kunde_dokument" on public.kunde_dokument
  for all
  to authenticated
  using (true)
  with check (true);
